document.addEventListener("DOMContentLoaded", () => {
    // DOM Elements
    const chatMessages = document.getElementById("chatMessages");
    const chatForm = document.getElementById("chatForm");
    const userInput = document.getElementById("userInput");
    const typingContainer = document.getElementById("typingContainer");
    const themeToggleBtn = document.getElementById("themeToggleBtn");
    const clearChatBtn = document.getElementById("clearChatBtn");

    // Chat Storage Key
    const LOCAL_STORAGE_KEY = "codealpha_chat_history";

    // Initialize Theme
    const savedTheme = localStorage.getItem("theme") || "dark";
    document.documentElement.setAttribute("data-theme", savedTheme);
    updateThemeIcon(savedTheme);

    // Load Chat History
    loadChatHistory();

    // Theme Toggle Handler
    themeToggleBtn.addEventListener("click", () => {
        const currentTheme = document.documentElement.getAttribute("data-theme");
        const newTheme = currentTheme === "dark" ? "light" : "dark";
        document.documentElement.setAttribute("data-theme", newTheme);
        localStorage.setItem("theme", newTheme);
        updateThemeIcon(newTheme);
    });

    function updateThemeIcon(theme) {
        themeToggleBtn.innerHTML = theme === "dark" 
            ? '<i class="fa-solid fa-sun"></i>' 
            : '<i class="fa-solid fa-moon"></i>';
    }

    // Form Submission
    chatForm.addEventListener("submit", async (e) => {
        e.preventDefault();
        const message = userInput.value.strip ? userInput.value.trim() : userInput.value;
        if (!message) return;

        // Display User Message
        appendMessage({
            sender: "user",
            text: message,
            timestamp: getFormattedTime()
        });

        userInput.value = "";
        showTypingIndicator(true);
        scrollToBottom();

        try {
            const response = await fetch("/chat", {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({ message })
            });

            const data = await response.json();
            showTypingIndicator(false);

            if (response.ok) {
                appendMessage({
                    sender: "bot",
                    text: data.answer,
                    source: data.source,
                    confidence: data.confidence,
                    timestamp: getFormattedTime()
                });
            } else {
                appendMessage({
                    sender: "bot",
                    text: data.answer || "An error occurred while connecting to server.",
                    source: "System Error",
                    timestamp: getFormattedTime()
                });
            }
        } catch (error) {
            showTypingIndicator(false);
            appendMessage({
                sender: "bot",
                text: "Network error: Unable to communicate with the backend API.",
                source: "System Error",
                timestamp: getFormattedTime()
            });
        }

        scrollToBottom();
    });

    // Clear Chat History
    clearChatBtn.addEventListener("click", () => {
        if (confirm("Are you sure you want to clear your conversation history?")) {
            localStorage.removeItem(LOCAL_STORAGE_KEY);
            chatMessages.innerHTML = "";
            appendWelcomeMessage();
        }
    });

    // Append Message to UI
    function appendMessage(msgObj, saveToStorage = true) {
        const row = document.createElement("div");
        row.classList.add("message-row", msgObj.sender);

        const isUser = msgObj.sender === "user";
        const avatarIcon = isUser ? "fa-user" : "fa-brain";

        let badgeHtml = "";
        if (!isUser && msgObj.source) {
            const isFaq = msgObj.source === "FAQ";
            const badgeClass = isFaq ? "faq" : "ai";
            const badgeText = isFaq ? "Answer from FAQ" : "Generated by AI";
            badgeHtml = `<span class="source-badge ${badgeClass}">${badgeText}</span>`;
        }

        row.innerHTML = `
            <div class="avatar">
                <i class="fa-solid ${avatarIcon}"></i>
            </div>
            <div class="bubble-container">
                <div class="chat-bubble">
                    ${escapeHtml(msgObj.text)}
                </div>
                <div class="meta-bar">
                    <span>${msgObj.timestamp}</span>
                    ${badgeHtml}
                    ${!isUser ? `<button class="copy-btn" title="Copy"><i class="fa-regular fa-copy"></i></button>` : ""}
                </div>
            </div>
        `;

        // Attach Copy Handler
        const copyBtn = row.querySelector(".copy-btn");
        if (copyBtn) {
            copyBtn.addEventListener("click", () => {
                navigator.clipboard.writeText(msgObj.text);
                copyBtn.innerHTML = '<i class="fa-solid fa-check"></i>';
                setTimeout(() => {
                    copyBtn.innerHTML = '<i class="fa-regular fa-copy"></i>';
                }, 2000);
            });
        }

        chatMessages.appendChild(row);

        if (saveToStorage) {
            saveMessageToHistory(msgObj);
        }
    }

    function showTypingIndicator(show) {
        if (show) {
            typingContainer.classList.remove("hidden");
        } else {
            typingContainer.classList.add("hidden");
        }
    }

    function scrollToBottom() {
        chatMessages.scrollTop = chatMessages.scrollHeight;
    }

    function getFormattedTime() {
        const now = new Date();
        return now.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    }

    function saveMessageToHistory(msgObj) {
        const history = JSON.parse(localStorage.getItem(LOCAL_STORAGE_KEY) || "[]");
        history.push(msgObj);
        localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(history));
    }

    function loadChatHistory() {
        const history = JSON.parse(localStorage.getItem(LOCAL_STORAGE_KEY) || "[]");
        if (history.length === 0) {
            appendWelcomeMessage();
        } else {
            history.forEach(msg => appendMessage(msg, false));
            scrollToBottom();
        }
    }

    function appendWelcomeMessage() {
        appendMessage({
            sender: "bot",
            text: "Hello! I am your CodeAlpha AI Assistant. Ask me anything about Computer Science, Neural Networks, Data Structures, or AI algorithms!",
            source: "FAQ",
            timestamp: getFormattedTime()
        }, false);
    }

    function escapeHtml(text) {
        const div = document.createElement("div");
        div.textContent = text;
        return div.innerHTML;
    }
});